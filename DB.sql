BEGIN;

CREATE TABLE companies (
    inn VARCHAR(12) PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    registration_date DATE,
    company_status VARCHAR(50),
    industry VARCHAR(255),
    bankruptcy_flag BOOLEAN NOT NULL DEFAULT FALSE,
    region_code VARCHAR(20),
    overdue_history_flag BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_companies_inn_length
        CHECK (CHAR_LENGTH(inn) IN (10, 12)),
    CONSTRAINT chk_companies_inn_digits
        CHECK (inn ~ '^[0-9]+$')
);

CREATE TABLE financial_statements (
    financial_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inn VARCHAR(12) NOT NULL,
    report_year INTEGER NOT NULL,
    report_quarter SMALLINT NOT NULL,
    revenue NUMERIC(18, 2),
    net_profit NUMERIC(18, 2),
    total_assets NUMERIC(18, 2),
    current_assets NUMERIC(18, 2),
    total_equity NUMERIC(18, 2),
    shortterm_liab NUMERIC(18, 2),
    long_term_liab NUMERIC(18, 2),

    CONSTRAINT fk_financial_statements_company
        FOREIGN KEY (inn)
        REFERENCES companies (inn)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_financial_statements_quarter
        CHECK (report_quarter BETWEEN 1 AND 4),
    CONSTRAINT chk_financial_statements_year
        CHECK (report_year >= 1900),
    CONSTRAINT uq_financial_statements_period
        UNIQUE (inn, report_year, report_quarter)
);

CREATE TABLE loan_catalog (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    description TEXT,
    business_category VARCHAR(20) NOT NULL,
    min_amount NUMERIC(18, 2) NOT NULL,
    max_amount NUMERIC(18, 2) NOT NULL,
    min_term_months INTEGER NOT NULL,
    max_term_months INTEGER NOT NULL,
    percent NUMERIC(5, 2) NOT NULL,
    loan_purpose VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_loan_catalog_business_category
        CHECK (business_category IN ('ip', 'ooo', 'both')),
    CONSTRAINT chk_loan_catalog_min_amount
        CHECK (min_amount >= 0),
    CONSTRAINT chk_loan_catalog_max_amount
        CHECK (max_amount >= min_amount),
    CONSTRAINT chk_loan_catalog_min_term
        CHECK (min_term_months > 0),
    CONSTRAINT chk_loan_catalog_max_term
        CHECK (max_term_months >= min_term_months),
    CONSTRAINT chk_loan_catalog_percent
        CHECK (percent >= 0)
);

CREATE TABLE loan_applications (
    application_id VARCHAR(36) PRIMARY KEY,
    inn VARCHAR(12) NOT NULL,
    product_id BIGINT NOT NULL,
    requested_amount NUMERIC(18, 2) NOT NULL,
    requested_term_months INTEGER NOT NULL,
    loan_purpose VARCHAR(50),
    application_status VARCHAR(30) NOT NULL DEFAULT 'submitted',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_loan_applications_company
        FOREIGN KEY (inn)
        REFERENCES companies (inn)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_loan_applications_product
        FOREIGN KEY (product_id)
        REFERENCES loan_catalog (product_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_loan_applications_amount
        CHECK (requested_amount > 0),
    CONSTRAINT chk_loan_applications_term
        CHECK (requested_term_months > 0),
    CONSTRAINT chk_loan_applications_status
        CHECK (
            application_status IN (
                'submitted',
                'processing',
                'manual_review',
                'approved',
                'rejected'
            )
        )
);

CREATE TABLE applications_checks (
    check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id VARCHAR(36) NOT NULL,
    product_id BIGINT NOT NULL,
    has_error BOOLEAN NOT NULL DEFAULT FALSE,
    risk_category VARCHAR(30),
    scoring INTEGER,
    scoring_factors JSONB,
    employee_rout BOOLEAN NOT NULL DEFAULT FALSE,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_applications_checks_application
        FOREIGN KEY (application_id)
        REFERENCES loan_applications (application_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_applications_checks_product
        FOREIGN KEY (product_id)
        REFERENCES loan_catalog (product_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE applications_decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id VARCHAR(36) NOT NULL,
    product_id BIGINT,
    decision_type VARCHAR(30) NOT NULL,
    decision_source VARCHAR(30) NOT NULL,
    decision_reason TEXT,
    approved_amount NUMERIC(18, 2),
    approved_term_months INTEGER,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_applications_decisions_application
        FOREIGN KEY (application_id)
        REFERENCES loan_applications (application_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_applications_decisions_product
        FOREIGN KEY (product_id)
        REFERENCES loan_catalog (product_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_applications_decisions_type
        CHECK (decision_type IN ('approved', 'rejected')),
    CONSTRAINT chk_applications_decisions_source
        CHECK (decision_source IN ('automatic', 'bank_employee')),
    CONSTRAINT chk_applications_decisions_amount
        CHECK (
            approved_amount IS NULL
            OR approved_amount >= 0
        ),
    CONSTRAINT chk_applications_decisions_term
        CHECK (
            approved_term_months IS NULL
            OR approved_term_months > 0
        ),
    CONSTRAINT chk_applications_decisions_approved_fields
        CHECK (
            decision_type <> 'approved'
            OR (
                product_id IS NOT NULL
                AND approved_amount IS NOT NULL
                AND approved_amount > 0
                AND approved_term_months IS NOT NULL
                AND approved_term_months > 0
            )
        )
);

CREATE TABLE applications_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id VARCHAR(36) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    old_status VARCHAR(30),
    new_status VARCHAR(30),
    event_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_applications_history_application
        FOREIGN KEY (application_id)
        REFERENCES loan_applications (application_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_applications_history_old_status
        CHECK (
            old_status IS NULL
            OR old_status IN (
                'submitted',
                'processing',
                'manual_review',
                'approved',
                'rejected'
            )
        ),
    CONSTRAINT chk_applications_history_new_status
        CHECK (
            new_status IS NULL
            OR new_status IN (
                'submitted',
                'processing',
                'manual_review',
                'approved',
                'rejected'
            )
        )
);

CREATE TABLE login (
    username VARCHAR(100) PRIMARY KEY,
    password TEXT NOT NULL,
    profile_type VARCHAR(20) NOT NULL,

    CONSTRAINT chk_login_profile_type
        CHECK (profile_type IN ('business', 'employee'))
);

CREATE INDEX idx_financial_statements_inn
    ON financial_statements (inn);

CREATE INDEX idx_financial_statements_period
    ON financial_statements (report_year, report_quarter);

CREATE INDEX idx_loan_catalog_active
    ON loan_catalog (is_active);

CREATE INDEX idx_loan_catalog_business_category
    ON loan_catalog (business_category);

CREATE INDEX idx_loan_applications_inn
    ON loan_applications (inn);

CREATE INDEX idx_loan_applications_product_id
    ON loan_applications (product_id);

CREATE INDEX idx_loan_applications_status
    ON loan_applications (application_status);

CREATE INDEX idx_applications_checks_application
    ON applications_checks (application_id);

CREATE INDEX idx_applications_checks_product
    ON applications_checks (product_id);

CREATE INDEX idx_applications_checks_application_product
    ON applications_checks (application_id, product_id);

CREATE INDEX idx_applications_decisions_application
    ON applications_decisions (application_id);

CREATE INDEX idx_applications_decisions_product
    ON applications_decisions (product_id);

CREATE INDEX idx_applications_decisions_latest
    ON applications_decisions (
        application_id,
        decided_at DESC,
        decision_id DESC
    );

CREATE INDEX idx_applications_history_application
    ON applications_history (application_id);

CREATE INDEX idx_applications_history_created_at
    ON applications_history (created_at);

COMMIT;
